'use strict';

/**
 * Regenerates src/data/question-counts.json from the real question bank.
 *
 *   node scripts/sync-question-counts.js
 *
 * WHY THIS EXISTS
 * The footer used to hardcode its category counts, and they rotted badly: it
 * still advertised "482+ soru", listed seven categories as "YAKINDA" with 5
 * questions each, and omitted Philosophy entirely — while the bank had 2400
 * questions across 12 finished categories. Visitors were being told the game
 * was half-built.
 *
 * The frontend cannot import server/questions.js (it is server-only and would
 * pull the whole 1.3 MB bank into the client bundle), so the counts are
 * generated into a small JSON file instead. tests/question_bank_test.js asserts
 * that file matches the live bank, so it can fail loudly rather than rot
 * quietly.
 */

const fs = require('fs');
const path = require('path');
const { QUESTIONS } = require('../server/questions');

const outPath = path.join(__dirname, '..', 'src', 'data', 'question-counts.json');

const categories = {};
let total = 0;
for (const [key, pool] of Object.entries(QUESTIONS)) {
  categories[key] = pool.length;
  total += pool.length;
}

const payload = {
  _comment: 'GENERATED by scripts/sync-question-counts.js — do not edit by hand.',
  total,
  categoryCount: Object.keys(categories).length,
  categories,
};

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');

console.log(`Wrote ${outPath}`);
console.log(`  ${payload.categoryCount} categories, ${payload.total} questions`);
