'use strict';

/**
 * Regenerates src/data/game-modes.json from server/gameModes.js.
 *
 *   node scripts/sync-game-modes.js
 *
 * WHY THIS EXISTS
 * Some UI copy has to name a win target BEFORE a room exists — the create form's
 * mode descriptions and the footer. Once a room exists the UI reads
 * room.winThreshold, which is authoritative; these are only for the copy that
 * comes first.
 *
 * Five call sites used to hardcode "100", and every one of them went stale the
 * moment the thresholds were rebalanced, telling players the wrong target.
 * Generating them from the server table and pinning the two together in
 * tests/game_modes_test.js means that can fail loudly instead of rotting.
 *
 * The frontend cannot import server/gameModes.js directly: it is CommonJS and
 * sits outside the tsconfig include, and pulling server modules into the client
 * bundle is how server-only code leaks.
 */

const fs = require('fs');
const path = require('path');
const { GAME_MODES } = require('../server/gameModes');

const outPath = path.join(__dirname, '..', 'src', 'data', 'game-modes.json');

const winThreshold = {};
const questionSeconds = {};
for (const [key, mode] of Object.entries(GAME_MODES)) {
  winThreshold[key] = mode.winThreshold;
  questionSeconds[key] = mode.questionSeconds;
}

const payload = {
  _comment: 'GENERATED by scripts/sync-game-modes.js — do not edit by hand.',
  winThreshold,
  questionSeconds,
  wagerOptions: GAME_MODES.wager.wagerOptions,
  wagerLossFactor: GAME_MODES.wager.lossFactor,
};

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');

console.log(`Wrote ${outPath}`);
console.log(`  targets: ${JSON.stringify(winThreshold)}`);
